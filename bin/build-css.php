<?php
/**
 * Builds assets/wintracker-isolated.css from assets/wintracker.css: the stylesheet used when
 * "Protect widgets from theme styles" is on (Wintracker → Settings → Display defaults).
 *
 * Every rule is scoped to the widget root with ID-level specificity, and a reset in front of it sends every
 * element inside a widget back to the browser's defaults, so ordinary theme rules (table, tr:first-child, td,
 * ul, a …) no longer reach the widgets. The theme's font and text colour still come through (they are inherited
 * from outside). Theme rules marked !important still win.
 *
 *     php bin/build-css.php          writes the file
 *     php bin/build-css.php --check  exits 1 if it is out of date (release workflow)
 */

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

$root = dirname( __DIR__ );
$src  = file_get_contents( $root . '/assets/wintracker.css' );

// The reset uses :where() so it weighs exactly (2,0,0): every plugin rule below is at least that and comes later.
// The widget root, matched twice through :is() with an id that never exists: specificity (2,0,0),
// above theme selectors like "#content table td" or ".entry-content tbody tr:first-child td".
const WT_ROOT = ':is(#wt-iso, .wintracker--isolated):is(#wt-iso, .wintracker--isolated)';

/** Splits a selector list at top-level commas. */
function wt_split( $selectors ) {
	$out   = array();
	$depth = 0;
	$buf   = '';
	foreach ( str_split( $selectors ) as $ch ) {
		$depth += '(' === $ch ? 1 : ( ')' === $ch ? -1 : 0 );
		if ( ',' === $ch && 0 === $depth ) {
			$out[] = trim( $buf );
			$buf   = '';
		} else {
			$buf .= $ch;
		}
	}
	$out[] = trim( $buf );
	return array_filter( $out, 'strlen' );
}

/** ".wintracker" -> ROOT, ".wintracker--mod x" -> ROOT.wintracker--mod x, anything else -> ROOT anything. */
function wt_scope( $selector ) {
	$selector = preg_replace( '/\s+/', ' ', $selector );
	if ( preg_match( '/^\.wintracker(?![\w-])(.*)$/s', $selector, $m ) ) {
		return WT_ROOT . $m[1];
	}
	if ( preg_match( '/^(\.wintracker--[\w-]+)(.*)$/s', $selector, $m ) ) {
		return WT_ROOT . $m[1] . $m[2];
	}
	return WT_ROOT . ' ' . $selector;
}

/** Rewrites a block of CSS (recursing into @media / @supports). */
function wt_rewrite( $css ) {
	$out = '';
	$i   = 0;
	$len = strlen( $css );
	while ( $i < $len ) {
		$open = strpos( $css, '{', $i );
		if ( false === $open ) {
			break;
		}
		$prelude = trim( substr( $css, $i, $open - $i ) );
		// Find the matching brace.
		$depth = 1;
		$j     = $open + 1;
		while ( $j < $len && $depth > 0 ) {
			$depth += '{' === $css[ $j ] ? 1 : ( '}' === $css[ $j ] ? -1 : 0 );
			$j++;
		}
		$body = substr( $css, $open + 1, $j - $open - 2 );
		if ( 0 === strpos( $prelude, '@media' ) || 0 === strpos( $prelude, '@supports' ) ) {
			$out .= $prelude . " {\n" . wt_rewrite( $body ) . "}\n";
		} else {
			$out .= implode( ",\n", array_map( 'wt_scope', wt_split( $prelude ) ) ) . " {" . rtrim( $body ) . "\n}\n";
		}
		$i = $j;
	}
	return $out;
}

$css    = preg_replace( '#/\*.*?\*/#s', '', $src );
$result = "/* Generated by bin/build-css.php from wintracker.css; do not edit. Used when \"Protect widgets from theme styles\" is on. */\n"
	. "/* Reset: everything inside a widget back to browser defaults (the theme's font and colour are still inherited). */\n"
	. WT_ROOT . ' :where(*:not(.wintracker__title)),' . "\n" . WT_ROOT . ' :where(*)::before,' . "\n" . WT_ROOT . " :where(*)::after {\n\tall: revert;\n}\n"
	. "/* The plugin's styles, scoped to the widget root. */\n"
	. wt_rewrite( $css );

$target = $root . '/assets/wintracker-isolated.css';
if ( in_array( '--check', $argv, true ) ) {
	$same = is_file( $target ) && file_get_contents( $target ) === $result;
	fwrite( $same ? STDOUT : STDERR, $same ? "assets/wintracker-isolated.css is up to date.\n" : "assets/wintracker-isolated.css is out of date: run php bin/build-css.php and commit it.\n" );
	exit( $same ? 0 : 1 );
}
file_put_contents( $target, $result );
echo "Wrote assets/wintracker-isolated.css.\n";
